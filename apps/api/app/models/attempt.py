import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    ForeignKeyConstraint,
    Identity,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class Attempt(Base):
    """One shot or try within a drill run. Totals and rates are derived by queries."""

    __tablename__ = "attempts"
    __table_args__ = (
        UniqueConstraint("drill_run_id", "attempt_number"),
        UniqueConstraint("owner_id", "idempotency_key"),
        ForeignKeyConstraint(
            ["owner_id", "drill_run_id"], ["drill_runs.owner_id", "drill_runs.id"]
        ),
        CheckConstraint("outcome IN ('success', 'fail', 'partial')", name="outcome_values"),
        CheckConstraint("attempt_number >= 1", name="attempt_number_positive"),
        CheckConstraint("points >= 0", name="points_non_negative"),
        CheckConstraint("duration_ms >= 0", name="duration_ms_non_negative"),
        Index("ix_attempts_drill_run_id", "drill_run_id"),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    owner_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("users.id"))
    drill_run_id: Mapped[int] = mapped_column(BigInteger)
    attempt_number: Mapped[int] = mapped_column(Integer)
    outcome: Mapped[str] = mapped_column(Text)
    points: Mapped[int | None] = mapped_column(Integer)
    duration_ms: Mapped[int | None] = mapped_column(Integer)
    # Generated by the client per tap; a replayed request returns the existing row.
    idempotency_key: Mapped[uuid.UUID]
    # Client time of the tap, and server time of receipt (kept for aligning video later).
    tapped_at: Mapped[datetime]
    recorded_at: Mapped[datetime] = mapped_column(server_default=func.now())
    # Undo sets voided_at; stats and set numbering ignore voided attempts.
    voided_at: Mapped[datetime | None]
    notes: Mapped[str | None] = mapped_column(Text)
